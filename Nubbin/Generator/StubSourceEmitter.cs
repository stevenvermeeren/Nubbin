using System.Text;
using Microsoft.CodeAnalysis;

namespace Nubbin.Generator;

internal static class StubSourceEmitter
{
    public static void Emit(SourceProductionContext context, INamedTypeSymbol type)
    {
        var methods = new MethodDiscoverer().GetSymbolsMissingImplementation(type).ToArray();
        var properties = new PropertyDiscoverer().GetSymbolsMissingImplementation(type).ToArray();
        var events = new EventDiscoverer().GetSymbolsMissingImplementation(type).ToArray();
        var storageProperties = properties.Where(SymbolFormatting.RequiresPropertyStorage).ToArray();
        if (methods.Length == 0 && properties.Length == 0 && events.Length == 0)
        {
            return;
        }

        var source = new StringBuilder();
        source.AppendLine("// <auto-generated />");
        source.Append("namespace ").AppendLine(type.ContainingNamespace.ToDisplayString());
        source.AppendLine("{");
        source.Indent(1).Append(SymbolFormatting.GetTypeAccessibility(type)).Append(" partial class ").AppendLine(type.Name);
        source.Indent(1).AppendLine("{");

        foreach (var method in methods)
        {
            AppendMethod(source, method, type);
        }

        foreach (var property in properties)
        {
            AppendProperty(source, type, property, storageProperties.Contains(property, SymbolEqualityComparer.Default));
        }

        foreach (var _event in events)
        {
            AppendEvent(source, type, _event);
        }

        source.Indent(1).AppendLine("}");
        if (storageProperties.Length > 0)
        {
            source.AppendLine("}");
            AppendPropertyStorage(source, type, storageProperties);
        }
        else
        {
            source.AppendLine("}");
        }

        context.AddSource(type.Name + ".Stub.g.cs", source.ToString());
    }

    private static void AppendMethod(StringBuilder source, IMethodSymbol method, ITypeSymbol type)
    {
        source.Indent(2).AppendLine(SymbolFormatting.GetMethodDeclaration(method, type));
        source.Indent(2).AppendLine("{");
        foreach (var parameter in method.Parameters.Where(parameter => parameter.RefKind == RefKind.Out))
        {
            if (StubDefaults.RequiresNotImplemented(parameter.Type, parameter.NullableAnnotation))
            {
                source.Indent(3).AppendLine("throw new global::System.NotImplementedException();");
            }
            else
            {
                source.Indent(3).Append(parameter.Name).Append(" = ")
                    .Append(StubDefaults.GetReturnExpression(parameter.Type, parameter.NullableAnnotation))
                    .AppendLine(";");
            }
        }

        if (StubDefaults.IsTask(method.ReturnType, out var taskResultType))
        {
            if (taskResultType is null)
            {
                source.Indent(3).AppendLine("return global::System.Threading.Tasks.Task.CompletedTask;");
            }
            else if (StubDefaults.RequiresNotImplemented(taskResultType))
            {
                source.Indent(3).AppendLine("throw new global::System.NotImplementedException();");
            }
            else
            {
                source.Indent(3).Append("return global::System.Threading.Tasks.Task.FromResult<")
                    .Append(taskResultType.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                    .Append(">(")
                    .Append(StubDefaults.GetReturnExpression(taskResultType))
                    .AppendLine(");");
            }
        }
        else if (!method.ReturnsVoid)
        {
            if (StubDefaults.RequiresNotImplemented(method.ReturnType))
            {
                source.Indent(3).AppendLine("throw new global::System.NotImplementedException();");
            }
            else
            {
                source.Indent(3).Append("return ").Append(StubDefaults.GetReturnExpression(method.ReturnType)).AppendLine(";");
            }
        }

        source.Indent(2).AppendLine("}");
    }

    private static void AppendProperty(
        StringBuilder source,
        INamedTypeSymbol type,
        IPropertySymbol property,
        bool useStorage)
    {
        source.Indent(2).Append(SymbolFormatting.GetPropertyDeclaration(property, type));
        if (!useStorage)
        {
            if (StubDefaults.RequiresNotImplemented(property.Type, property.NullableAnnotation))
            {
                source.AppendLine();
                source.Indent(2).AppendLine("{");
                source.Indent(3).AppendLine("get => throw new global::System.NotImplementedException();");
                source.Indent(3).AppendLine("set { }");
                source.Indent(2).AppendLine("}");
                return;
            }

            source.Append(" { get; set; } = ").Append(StubDefaults.GetReturnExpression(property.Type, property.NullableAnnotation)).AppendLine(";");
            return;
        }

        source.AppendLine();
        source.Indent(2).AppendLine("{");
        if (SymbolFormatting.HasGetter(property))
        {
            source.Indent(3).Append("get => global::Nubbin.Stubs")
                .Append(".GetPropertyHelper(this).").Append(property.Name).AppendLine(";");
        }
        if (SymbolFormatting.HasSetter(property))
        {
            source.Indent(3).Append("set => global::Nubbin.Stubs")
                .Append(".GetPropertyHelper(this).").Append(property.Name).AppendLine(" = value;");
        }
        source.Indent(2).AppendLine("}");
    }

    private static void AppendEvent(
        StringBuilder source,
        INamedTypeSymbol type,
        IEventSymbol _event)
    {
        source.Indent(2).Append(SymbolFormatting.GetEventDeclaration(_event, type))
            .AppendLine(" { add { } remove { } }");
    }

    private static void AppendPropertyStorage(
        StringBuilder source,
        INamedTypeSymbol type,
        IReadOnlyCollection<IPropertySymbol> properties)
    {
        var typeName = type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);
        var propertiesTypeName = GetPropertyStorageTypeName(type);
        var qualifiedPropertiesTypeName = GetQualifiedPropertyStorageTypeName(type);
        var accessibility = SymbolFormatting.GetGeneratedTypeAccessibility(type);

        source.AppendLine("namespace Nubbin");
        source.AppendLine("{");
        source.Indent(1).Append(accessibility).AppendLine(" static partial class Stubs");
        source.Indent(1).AppendLine("{");
        source.Indent(2).Append(accessibility).Append(" static ").Append(qualifiedPropertiesTypeName)
            .Append(" GetPropertyHelper(this ").Append(typeName).AppendLine(" owner)");
        source.Indent(3).Append("=> global::Nubbin.StubPropertyStorage<").Append(typeName).Append(", ")
            .Append(qualifiedPropertiesTypeName).AppendLine(">.Get(owner);");
        source.Indent(1).AppendLine("}");
        source.AppendLine("}");
        source.Append("namespace ").AppendLine(GetPropertyHelperNamespace(type));
        source.AppendLine("{");
        source.Indent(1).Append(accessibility).Append(" sealed class ").AppendLine(propertiesTypeName);
        source.Indent(1).AppendLine("{");
        foreach (var property in properties)
        {
            source.Indent(2).Append("public ")
                .Append(property.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat))
                .Append(' ').Append(property.Name);
            if (StubDefaults.RequiresNotImplemented(property.Type, property.NullableAnnotation))
            {
                source.AppendLine();
                source.Indent(2).AppendLine("{");
                source.Indent(3).AppendLine("get => throw new global::System.NotImplementedException();");
                source.Indent(3).AppendLine("set { }");
                source.Indent(2).AppendLine("}");
            }
            else
            {
                source.Append(" { get; set; } = ")
                    .Append(StubDefaults.GetReturnExpression(property.Type, property.NullableAnnotation)).AppendLine(";");
            }
        }
        source.Indent(1).AppendLine("}");
        source.AppendLine("}");
    }

    private static string GetPropertyStorageTypeName(INamedTypeSymbol type)
    {
        return type.Name + "PropertyHelper";
    }

    private static string GetQualifiedPropertyStorageTypeName(INamedTypeSymbol type)
    {
        return "global::" + GetPropertyHelperNamespace(type) + "." + GetPropertyStorageTypeName(type);
    }

    private static string GetPropertyHelperNamespace(INamedTypeSymbol type)
    {
        var namespaceName = type.ContainingNamespace.ToDisplayString();
        return string.IsNullOrEmpty(namespaceName) ? "Nubbin" : namespaceName + ".Nubbin";
    }

    private static StringBuilder Indent(this StringBuilder source, int level)
    {
        for (var i = 0; i < level; i++)
        {
            source.Append("    ");
        }

        return source;
    }
}